def detect_groups(text: str) -> list[str]:
    """Мәтінде қандай топтар іске қосылғанын қайтарады (топ атаулары)."""
    if not isinstance(text, str):
        return []
    low = text.lower()
    return [g for g, langs in RULES.items()
            if any(p in low for phrases in langs.values() for p in phrases)]


def count_groups(text: str) -> int:
    return len(detect_groups(text))
